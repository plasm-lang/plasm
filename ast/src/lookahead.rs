/// The same as `std::iter::Peekable`, but with a fixed-size lookahead buffer of size `N`.
pub struct Lookahead<I, const N: usize>
where
    I: Iterator,
{
    inner: I,
    lookahead: [Option<I::Item>; N],
}

impl<I, const N: usize> Lookahead<I, N>
where
    I: Iterator,
{
    pub fn new(mut inner: I) -> Self {
        Self {
            lookahead: std::array::from_fn(|_| inner.next()),
            inner,
        }
    }

    pub fn peek(&self) -> Option<&I::Item> {
        self.peek_nth(0)
    }

    pub fn peek_nth(&self, n: usize) -> Option<&I::Item> {
        debug_assert!(n < N, "Lookahead index out of bounds");
        self.lookahead.get(n)?.as_ref()
    }
}

impl<I, const N: usize> Iterator for Lookahead<I, N>
where
    I: Iterator,
{
    type Item = I::Item;

    fn next(&mut self) -> Option<Self::Item> {
        if N == 0 {
            return self.inner.next();
        }

        self.lookahead.rotate_left(1);
        std::mem::replace(&mut self.lookahead[N - 1], self.inner.next())
    }
}

